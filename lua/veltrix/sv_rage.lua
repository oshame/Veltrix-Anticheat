-- Server-observed rage / anti-aim heuristics. Unusual input is not proof of cheating.
if not SERVER then return end

local C = Veltrix.Cfg
local samples = setmetatable({}, { __mode = "k" })
local function eligible(p)
    return IsValid(p) and p:IsPlayer() and not p:IsBot() and p:Alive()
        and not p:InVehicle() and p:GetObserverMode() == OBS_MODE_NONE
        and p:GetMoveType() == MOVETYPE_WALK
        and CurTime() >= (p.VeltrixIgnoreUntil or 0)
end
local function log(p, source, message)
    if not C("diagnostics_enabled") then return end
    Veltrix.AddLog({ t = os.time(), name = p:Nick(), sid = p:SteamID(),
        src = source, pts = 0, score = math.Round(Veltrix.GetState(p).score, 2),
        info = true, detail = string.sub(message, 1, 200) })
end
local function delta(a, b)
    return math.abs(math.AngleDifference(a, b))
end
local function reset(p)
    samples[p] = nil
end
hook.Add("PlayerSpawn", "Veltrix_RageSpawn", reset)
hook.Add("PlayerDisconnected", "Veltrix_RageDisconnect", reset)

hook.Add("StartCommand", "Veltrix_RageCommands", function(p, cmd)
    if not C("rage_monitor_enabled") or not eligible(p) then reset(p) return end
    local id = cmd:CommandNumber()
    if id <= 0 then return end
    local a = cmd:GetViewAngles()
    local now = CurTime()
    local s = samples[p]
    if not s then
        s = { jitter = 0, spin = 0, reversals = 0, fireSnaps = 0, alerts = {}, last = nil }
        samples[p] = s
    end
    if not s.last or (s.id and id ~= s.id + 1) or (s.time and now - s.time > 0.3) then
        s.last, s.id, s.time = Angle(a.p, a.y, a.r), id, now
        s.jitter, s.spin, s.reversals, s.fireSnaps = 0, 0, 0, 0
        s.prevYawChange = nil
        return
    end
    local yawChange = math.AngleDifference(a.y, s.last.y)
    local pitchChange = delta(a.p, s.last.p)
    local yawAbs = math.abs(yawChange)
    local attacking = cmd:KeyDown(IN_ATTACK)

    -- Fast spin / oscillation can be generated by unusual legitimate controls.
    -- Require repeated consecutive samples; these checks are diagnostics only.
    if yawAbs >= C("rage_spin_degrees") and yawAbs <= 179.9 then
        s.spin = s.spin + 1
    else
        s.spin = math.max(0, s.spin - 2)
    end
    if s.prevYawChange and yawAbs >= C("rage_jitter_degrees")
        and math.abs(s.prevYawChange) >= C("rage_jitter_degrees")
        and yawChange * s.prevYawChange < 0 then
        s.jitter = s.jitter + 1
    else
        s.jitter = math.max(0, s.jitter - 1)
    end
    if attacking and (yawAbs >= 75 or pitchChange >= 60) then
        s.fireSnaps = s.fireSnaps + 1
    else
        s.fireSnaps = math.max(0, s.fireSnaps - 1)
    end
    local function report(key, threshold, description)
        if s[key] < threshold or now < (s.alerts[key] or 0) then return end
        s.alerts[key] = now + 20
        log(p, "rage_" .. key, description .. " (" .. s[key] .. " consecutive-pattern samples)")
    end
    report("spin", 12, "Repeated large yaw rotation in consecutive usercmds")
    report("jitter", 10, "Repeated rapid alternating yaw in usercmds")
    report("fireSnaps", 5, "Repeated extreme aim changes while attack held")
    s.prevYawChange = yawChange
    s.last, s.id, s.time = Angle(a.p, a.y, a.r), id, now
end)
